assert URL.startswith(('http://127.0.0.1:','http://localhost:'))
OUT=Path(__file__).resolve().parent.parent/'qa-output'/'expedition';OUT.mkdir(parents=True,exist_ok=True)
checks=[];errors=[]
def check(name,value,detail=None):
 checks.append({'name':name,'pass':bool(value),'detail':detail})
 (OUT/'browser.json').write_text(json.dumps({'checks':checks,'errors':errors},indent=2))
 assert value,(name,detail)
with sync_playwright() as pw:
 browser=pw.chromium.launch(executable_path=r'C:\Program Files\Google\Chrome\Application\chrome.exe',headless=True,args=['--no-first-run','--disable-extensions','--disable-background-networking'])
 context=browser.new_context(viewport={'width':1280,'height':800})
 p=context.new_page();p.on('pageerror',lambda e:errors.append(str(e)));p.on('console',lambda m:print('CONSOLE',m.type,m.text[:900]) if m.type=='error' else None)
 p.goto(URL+'?debug=1');p.wait_for_function('window.__REEF__',timeout=60000);p.add_style_tag(content='#debug-stats{display:none!important}');p.wait_for_timeout(1400)
 check('boot renders',p.locator('#loading').is_hidden(),p.locator('#loading').inner_text())
 p.screenshot(path=str(OUT/'harbour-desktop.png'))
 p.locator('[data-action=boat-launch]').click();p.wait_for_timeout(1200)
 check('boat launch enabled',p.locator('body').evaluate("e=>e.classList.contains('boat-travel')"))
 p.keyboard.down('w');p.wait_for_timeout(3500);p.keyboard.up('w');p.screenshot(path=str(OUT/'boat-moving.png'))
 check('moving boat readout', 'knots' in p.locator('#boat-status').inner_text())
 p.locator('#boat-return').click();p.evaluate("__REEF__.dispatch('dive')");p.wait_for_timeout(1000)
 check('dive entered',p.evaluate("!__REEF__.paused && !!__REEF__.sim"));p.screenshot(path=str(OUT/'reef-desktop.png'))
 p.evaluate("__REEF__.dispatch('screen','journal')");p.screenshot(path=str(OUT/'chart-gardens.png'))
 p.evaluate("__REEF__.dispatch('close')")
 # Make a landed-catch fixture, exhaust permanent fish, then reproduce the old failure.
 p.evaluate("""()=>{let q=__REEF__,s=q.sim,r=s.run;q.profile.reefs.gardens.removed=r.fish.map(f=>f.id);r.cargo=r.fish.slice(0,4).map(f=>({id:f.id,weight:f.weight,size:f.size,value:20}));s.finish(false);q.tick(.02);}""")
 check('debrief opens',p.evaluate("__REEF__.ui.screen==='debrief'"))
 p.locator('[data-screen=scaling]').click();p.wait_for_timeout(500);p.screenshot(path=str(OUT/'scaling-3d.png'))
 for i in range(3):p.evaluate("__REEF__.ui.miniPosition=[.3,.56,.78][__REEF__.ui.miniScores.length];__REEF__.ui.miniReady=0;__REEF__.ui.miniAction()")
 p.locator('[data-screen=filleting]').click();p.wait_for_timeout(500);p.screenshot(path=str(OUT/'filleting-3d.png'))
 for i in range(3):p.evaluate("__REEF__.ui.filletBladeX=[109,176,242][__REEF__.ui.filletStage];__REEF__.ui.filletReadyAt=0;__REEF__.ui.tryFilletCut()")
 p.locator('[data-action=fillet-cancel]').click();p.locator('[data-screen=cooking]').click();p.wait_for_timeout(300);p.screenshot(path=str(OUT/'cooking.png'))
 for i in range(3):p.evaluate("__REEF__.ui.miniPosition=[.30,.62,.46][__REEF__.ui.miniScores.length];__REEF__.ui.miniReady=0;__REEF__.ui.miniAction()")
 p.locator('[data-close]').first.click();check('allocation retained',p.locator('[data-allocate=sell]').input_value()=='4')
 p.locator('#settle').click();check('receipt replaces exhausted-reef debrief',p.evaluate("__REEF__.ui.screen==='receipt' && !__REEF__.profile.pending && __REEF__.profile.day===2"));p.screenshot(path=str(OUT/'receipt.png'))
 cash=p.evaluate('__REEF__.profile.cash');p.evaluate("__REEF__.dispatch('settle')");check('repeat settle has no payout',p.evaluate('__REEF__.profile.cash')==cash)
