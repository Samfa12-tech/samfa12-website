"""Original low-poly organic field-response asset. Blender 5.2, no external assets.
Run: blender --background --python scripts/author-crown-of-thorns.py
Retains a smooth editable body, bent arms and restrained angled papillae.
"""
import bpy,math,json
from pathlib import Path
from mathutils import Vector
ROOT=Path(__file__).resolve().parents[1];OUT=ROOT/'art'/'crown-of-thorns';OUT.mkdir(parents=True,exist_ok=True)
bpy.ops.object.select_all(action='SELECT');bpy.ops.object.delete(use_global=False)
def material(name,color):
 m=bpy.data.materials.new(name);m.diffuse_color=(*color,1);m.use_nodes=True;m.node_tree.nodes['Principled BSDF'].inputs['Base Color'].default_value=(*color,1);m.node_tree.nodes['Principled BSDF'].inputs['Roughness'].default_value=.7;return m
bodymat=material('Mottled plum living tissue',(.54,.31,.46));tipmat=material('Pale lavender papillae',(.76,.62,.69))
verts=[(0,0,.22)];faces=[];segments=13*10;rings=7
for ring in range(1,rings+1):
 f=ring/rings
 for i in range(segments):
  a=i/segments*math.tau;arm=math.floor(i/10);u=(i%10)/10
  reach=.32+(.40+.075*math.sin(arm*2.7))*((math.cos((u-.5)*math.tau)+1)/2)**2.6
  bend=.16*math.sin(arm*1.8)*f*f
  d=f*reach;z=.035+.16*(1-f*f)+.016*math.sin(a*13+f*9)*(1-f*.7)
  verts.append((math.cos(a+bend)*d,math.sin(a+bend)*d,z))
for i in range(segments):faces.append((0,1+i,1+(i+1)%segments))
for ring in range(rings-1):
 a=1+ring*segments;b=a+segments
 for i in range(segments):j=(i+1)%segments;faces.append((a+i,b+i,b+j,a+j))
bottom=len(verts);verts.append((0,0,.018))
for i in range(segments):faces.append((bottom,1+(rings-1)*segments+(i+1)%segments,1+(rings-1)*segments+i))
mesh=bpy.data.meshes.new('Continuous scalloped body with bent tapering arms');mesh.from_pydata(verts,[],faces);mesh.update()
body=bpy.data.objects.new('Crown of thorns — 13 organic arms',mesh);bpy.context.collection.objects.link(body);body.data.materials.append(bodymat)
for p in body.data.polygons:p.use_smooth=True
objects=[body]
for arm in range(13):
 for k in range(4):
  f=.22+k*.17;a=(arm+.5)/13*math.tau+.16*math.sin(arm*1.8)*f*f;d=f*(.72+.075*math.sin(arm*2.7));z=.035+.16*(1-f*f)
  root=Vector((math.cos(a)*d,math.sin(a)*d,z));end=root+Vector((math.cos(a)*.025,math.sin(a)*.025,.060+.018*math.sin(arm+k)))
  delta=end-root;bpy.ops.mesh.primitive_cone_add(vertices=5,radius1=.014,radius2=.002,depth=delta.length,location=(root+end)/2)
  obj=bpy.context.object;obj.name='Short angled papilla';obj.rotation_euler=delta.to_track_quat('Z','Y').to_euler();obj.data.materials.append(tipmat);objects.append(obj)
bpy.ops.object.select_all(action='DESELECT')
for obj in objects:obj.select_set(True)
bpy.ops.export_scene.gltf(filepath=str(OUT/'crown-of-thorns.glb'),use_selection=True,export_format='GLB')
data={key:[] for key in ['positions','normals','colors','uvs','indices']}
for obj in objects:
 me=obj.data;me.calc_loop_triangles();color=obj.data.materials[0].diffuse_color[:3]
 for tri in me.loop_triangles:
  for vi in tri.vertices:
   v=obj.matrix_world@me.vertices[vi].co;n=obj.matrix_world.to_3x3()@(me.vertices[vi].normal if obj==body else tri.normal);n.normalize()
   data['indices'].append(len(data['positions'])//3);data['positions'].extend(round(float(x),5) for x in [v.x,v.z,v.y]);data['normals'].extend(round(float(x),5) for x in [n.x,n.z,n.y]);data['colors'].extend([round(float(x),4) for x in color]+[1]);data['uvs'].extend([0,0])
(ROOT/'src'/'render'/'assets'/'crown-of-thorns.ts').write_text('// Original Blender mesh. Generated by author-crown-of-thorns.py; +Y up, metres.\nexport const crownOfThorns = '+json.dumps(data,separators=(',',':'))+';\n')
(OUT/'asset-manifest.json').write_text(json.dumps({'origin':'Samfa12 original Blender authoring','triangles':len(data['indices'])//3,'draws':1,'textures':0,'maximumRadiusMetres':.8,'collision':'Ambient job target; no solid player collider','ordinarySeaStars':'Separate orange five-arm ambient mesh, never a treatment target'},indent=2))
scene=bpy.context.scene;scene.world.color=(.14,.19,.19)
bpy.ops.object.light_add(type='AREA',location=(1,-2,4));bpy.context.object.data.energy=400;bpy.context.object.data.size=4
bpy.ops.object.camera_add(location=(1.3,-1.6,2.1));camera=bpy.context.object;camera.rotation_euler=(Vector((0,0,.1))-camera.location).to_track_quat('-Z','Y').to_euler();camera.data.type='ORTHO';camera.data.ortho_scale=1.9;scene.camera=camera
scene.render.engine='CYCLES';scene.cycles.samples=24;scene.render.resolution_x=900;scene.render.resolution_y=760;scene.render.resolution_percentage=100;scene.render.filepath=str(OUT/'blender-crown-of-thorns.png')
bpy.ops.wm.save_as_mainfile(filepath=str(OUT/'crown-of-thorns.blend'));bpy.ops.render.render(write_still=True)
print('CROWN_OF_THORNS',len(data['indices'])//3,'triangles')
